func blokletters(naam string) string {
	rijen := make([]string, 5)
	eerste := true
	for _, r := range strings.ToUpper(naam) {
		g, ok := blokFont[r]
		if !ok {
			continue
		}
		for k := range rijen {
			if !eerste {
				rijen[k] += " "
			}
			rijen[k] += strings.ReplaceAll(g[k], "#", "█")
		}
		eerste = false
	}
	if eerste {
		return blokletters("UNSCROLL")
	}
	return strings.Join(rijen, "\n")
}
